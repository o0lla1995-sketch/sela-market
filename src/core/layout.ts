/**
 * layout.ts — إخلاء أسفل الشاشات فوق القائمة السفلية وشريط الإيماءات.
 * ─────────────────────────────────────────────────────────────────
 * شكوى المستخدم المتكررة: «هامش المسافة لآخر الصفحات أعلى من القائمة
 * السفلية» — آخر محتوى الصفحات يختفي خلف شريط التبويبات السفلي.
 * القاعدة (v2.1):
 *  • شاشات التبويبات (الرئيسية/المتاجر/السلة/الطلبات/حسابي): القائمة
 *    السفلية ~64 + شريط النظام — إخلاء ≥ 96dp مع الحد الأدنى.
 *  • الشاشات المدفوعة فوقها (متجر/منتج/دفع…): إخلاء شريط الإيماءات
 *    + هامش تنفّس.
 */
import {useSafeAreaInsets} from 'react-native-safe-area-context';

/** إخلاء شاشة تبويب — يفوق ارتفاع القائمة السفلية + شريط النظام. */
export function useTabBottomClearance(): number {
  const insets = useSafeAreaInsets();
  return Math.max(insets.bottom + 24, 96);
}

/** إخلاء شاشة مدفوعة (فوق القائمة السفلية) — شريط الإيماءات + تنفس. */
export function useStackBottomClearance(): number {
  const insets = useSafeAreaInsets();
  return insets.bottom + 40;
}
