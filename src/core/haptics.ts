/**
 * haptics.ts — الاهتزاز اللمسي للأفعال الحرجة (الجولة 62):
 * طلب التاجر: «تفاعلات لمسية أنيقة — اهتزاز خفيف عند الدفع والمفضلة».
 * نستخدم واجهة Vibration المدمجة في RN (بلا اعتماديات أصلية إضافية):
 * نبضة قصيرة جداً (8ms) تُحسّ كانتقاض خفيف لا كجرس — نفس إحساس
 * «light impact» في تطبيقات التجزئة العالمية.
 *
 * ملاحظة أندرويد: بعض الأجهزة الرخيصة تتجاهل المدد الأقصر من ~10ms
 * ونضربها في معامل أمان بسيط. الدالة صامتة تماماً عند أي فشل —
 * الاهتزاز تحسين ولا يجوز أن يكسر أي مسار أبداً.
 */
import {Vibration, Platform} from 'react-native';

/** نبضة خفيفة — للأفعال الصغيرة (مفضلة، اختيار مواصفة). */
export function hapticLight(): void {
  try {
    Vibration.vibrate(Platform.OS === 'android' ? 10 : 8);
  } catch {
    /* صمت — تحسين اختياري */
  }
}

/** نبضة تأكيد متوسطة — للأفعال الحرجة (إضافة للسلة، إتمام الطلب). */
export function hapticSuccess(): void {
  try {
    Vibration.vibrate(Platform.OS === 'android' ? 16 : 12);
  } catch {
    /* صمت */
  }
}
